#!/usr/bin/env node
// Builds evals/RESULTS.md from evals/results/<label>.json, in the order given on the command line.
//   node evals/report.js baseline-plasma4-mobile iter1 iter2 ...
const fs=require('fs');
const path=require('path');
const labels=process.argv.slice(2);
const runs=labels.map(l=>JSON.parse(fs.readFileSync(path.join(__dirname,'results',l+'.json'),'utf8')));
const ids=[...new Set(runs.flatMap(r=>r.results.map(x=>x.id)))].sort((a,b)=>+a.slice(1)-+b.slice(1));
const byId=(run,id)=>run.results.find(x=>x.id===id);
const cell=x=>!x?'–':x.pass===null?'n/a':x.pass?'✅':'❌';
const fmt=v=>v===null||v===undefined?'–':typeof v==='number'?(Math.round(v*10)/10)+'':v;

let md='# Eval results\n\nGenerated by `node evals/report.js '+labels.join(' ')+'`.\n\n';
md+='| Run | Target | Passed | Score |\n|---|---|---|---|\n';
for (const r of runs) md+=`| ${r.label} | \`${r.target}\` | ${r.passed}/${r.total} | ${r.score} |\n`;
md+='\n## Per eval\n\n| ID | Group | Eval | '+runs.map(r=>r.label).join(' | ')+' |\n|---|---|---|'+runs.map(()=>'---').join('|')+'|\n';
for (const id of ids){
	const any=runs.map(r=>byId(r,id)).find(Boolean);
	md+=`| ${id} | ${any.group} | ${any.name} | `+runs.map(r=>cell(byId(r,id))).join(' | ')+' |\n';
}
md+='\n## Metrics\n\n| Metric | '+runs.map(r=>r.label).join(' | ')+' |\n|---|'+runs.map(()=>'---').join('|')+'|\n';
const metrics=[...new Set(runs.flatMap(r=>r.results.flatMap(x=>Object.keys(x.metrics||{}).map(k=>x.id+' '+k))))];
for (const m of metrics){
	const [id,k]=m.split(' ');
	md+=`| ${id} ${k} | `+runs.map(r=>{const x=byId(r,id);return fmt(x&&x.metrics?x.metrics[k]:null);}).join(' | ')+' |\n';
}
md+='\n## Failures in the latest run\n\n';
const last=runs[runs.length-1];
const fails=last.results.filter(x=>x.pass===false);
md+=fails.length?fails.map(x=>`- **${x.id}** ${x.name}: \`${JSON.stringify(x.detail).slice(0,300)}\``).join('\n')+'\n':'None.\n';
fs.writeFileSync(path.join(__dirname,'RESULTS.md'),md);
console.log(md);
